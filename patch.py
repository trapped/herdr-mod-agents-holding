def write(path, text):
    if path.exists() and path.read_text() == text:
        return False
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    tmp.write_text(text)
    os.replace(tmp, path)
    return True


def main():
    try:
        src = (SHIPPED / "main.js").read_text()
    except OSError:
        sys.exit("agents-holding: Herdr's own agents mod isn't there yet (start Herdr once), skipped")
    for old, new in EDITS:
        if src.count(old) != 1:
            sys.exit(f"agents-holding: Herdr's agents mod changed, this edit no longer fits: {old.strip()[:70]}")
        src = src.replace(old, new)
    src = "// GENERATED by patch.py from mods/agents/main.js: edit patch.py, not this file.\n" + src
    changed = write(HERE / "main.js", src)
    changed = write(HERE / "mod.json", (SHIPPED / "mod.json").read_text()) or changed
    if changed:
        print("updated mods/agents-holding")


if __name__ == "__main__":
    main()
